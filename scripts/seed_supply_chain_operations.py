def mysql(sql: str) -> list[list[str]]:
    host = os.environ.get("CLOUDMOLD_MYSQL_HOST")
    if host:
        command = ["mysql", "-N", "-B", "-h", host, "-u", os.environ.get("CLOUDMOLD_MYSQL_USER", "root"), MYSQL_DATABASE, "-e", sql]
    ssl_ca = os.environ.get("CLOUDMOLD_MYSQL_SSL_CA")
    if ssl_ca:
        # The local MySQL image uses a CA-pinned autogenerated server
        # certificate without a DNS subjectAltName. VERIFY_CA keeps TLS and
        # CA verification without asking it to satisfy that absent hostname
        # extension inside the Compose network.
        ssl_mode = os.environ.get("CLOUDMOLD_MYSQL_SSL_MODE")
        ssl_arguments = ["--ssl-ca=" + ssl_ca]
        if ssl_mode:
            ssl_arguments.append("--ssl-mode=" + ssl_mode)
        else:
            ssl_arguments.append("--skip-ssl-verify-server-cert")
        command[1:1] = ssl_arguments
        environment = os.environ.copy()
        password = environment.get("CLOUDMOLD_MYSQL_PASSWORD")
        if password:
            environment["MYSQL_PWD"] = password
    else:
        command = ["docker", "exec", "yudao-mysql", "mysql", "-uroot", "-p123456", "-N", "-B", "-e", sql]
        environment = None
    completed = subprocess.run(command, text=True, capture_output=True, check=False, env=environment)
    if completed.returncode:
        raise RuntimeError(completed.stderr.strip() or "automation database query failed")
    return [line.split("\t") for line in completed.stdout.splitlines() if line.strip()]


def access_token() -> str:
    rows = mysql(
        f"SELECT refresh_token FROM `{MYSQL_DATABASE}`.system_oauth2_access_token "
        f"WHERE tenant_id={TENANT_ID} AND user_id={OPERATOR_ID} AND expires_time>UTC_TIMESTAMP(6) "
        "ORDER BY expires_time DESC LIMIT 1"
    )
    if not rows:
        raise RuntimeError("no active automation operator refresh token")
    url = BASE_URL + "/system/auth/refresh-token?refreshToken=" + urllib.parse.quote(rows[0][0], safe="")
    request = urllib.request.Request(url, data=b"", method="POST", headers={"tenant-id": str(TENANT_ID)})
    with urllib.request.urlopen(request, timeout=30) as response:
        payload = json.load(response)
    token = payload.get("data", {}).get("accessToken") if payload.get("code") == 0 else None
    if not token:
        raise RuntimeError("automation operator token refresh failed")
    return token


def api(method: str, path: str, body: dict | None = None) -> dict:
    global TOKEN
    if TOKEN is None:
        TOKEN = access_token()
    request = urllib.request.Request(
        BASE_URL + path,
        data=None if body is None else json.dumps(body, ensure_ascii=False, separators=(",", ":")).encode(),
        method=method,
        headers={"Authorization": "Bearer " + TOKEN, "tenant-id": str(TENANT_ID), "Content-Type": "application/json"},
    )
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            payload = json.load(response)
    except urllib.error.HTTPError as error:
        raise RuntimeError(error.read().decode()) from error
    if payload.get("code") != 0:
        raise RuntimeError(json.dumps(payload, ensure_ascii=False))
    return payload.get("data") or {}


def now() -> str:
    return dt.datetime.now(dt.timezone.utc).isoformat().replace("+00:00", "Z")


def new_id() -> str:
    return str(uuid.uuid4())


def sha(value: str) -> str:
    return hashlib.sha256(value.encode()).hexdigest()


def command(operation: str, suffix: str, **fields: object) -> dict:
    return {"operation": operation, "idempotencyKey": "candidate-" + suffix,
            "sourceEventId": "supply-operations-" + suffix, "correlationId": new_id(),
            "occurredAt": now(), "actorPrincipalId": PRINCIPAL, **fields}


def balance(where: str, offset: int = 0) -> list[str]:
    rows = mysql(
        "SELECT balance_id,owner_type,owner_id,canonical_sku_id,warehouse_id,location_id,"
        "COALESCE(lot_id,''),stock_status,quality_status,base_uom_code,on_hand_quantity "
        f"FROM `{MYSQL_DATABASE}`.cloudmold_inventory_balance_v3 WHERE tenant_id={TENANT_ID} AND {where} "
        f"ORDER BY updated_at DESC LIMIT 1 OFFSET {max(0, offset)}"
    )
    if not rows:
        raise RuntimeError("no eligible inventory balance")
    return rows[0]


def transferable_balance(offset: int = 0) -> list[str]:
    rows = mysql(
        "SELECT b.balance_id,b.owner_type,b.owner_id,b.canonical_sku_id,b.warehouse_id,b.location_id,"
        "b.lot_id,b.stock_status,b.quality_status,b.base_uom_code,b.on_hand_quantity "
        f"FROM `{MYSQL_DATABASE}`.cloudmold_inventory_balance_v3 b "
        f"JOIN `{MYSQL_DATABASE}`.cloudmold_inventory_lot l "
        "ON l.tenant_id=b.tenant_id AND l.lot_id=b.lot_id "
        f"WHERE b.tenant_id={TENANT_ID} AND l.status='ACTIVE' AND b.on_hand_quantity>=1 "
        "AND b.stock_status='SELLABLE' AND b.quality_status='QUALIFIED' "
        f"AND b.warehouse_id<>'{TARGET_WAREHOUSE_ID}' "
        f"ORDER BY b.updated_at DESC LIMIT 1 OFFSET {max(0, offset)}"
    )
    if not rows:
        raise RuntimeError("no active inventory lot is eligible for warehouse transfer")
    return rows[0]


