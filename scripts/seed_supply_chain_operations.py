def enqueue(kind: str, payload: dict, sequence: int) -> dict:
    skill_id, schedule_suffix = SKILLS[kind]
    nonce = dt.datetime.now(dt.timezone.utc).strftime("%Y%m%d%H%M%S") + "-" + uuid.uuid4().hex[:10]
    candidate = api("POST", "/cloudmold/ai-operations/temporal-automation/candidates", {
        "clientRequestKey": f"supply-operations-{kind}-{nonce}", "skillId": skill_id, "skillVersion": "1.0.0",
        "businessKey": f"supply-operations/{kind}/{nonce}", "inputJson": json.dumps(payload, ensure_ascii=False, separators=(",", ":")),
    })
    schedule_id = f"cloudmold-t{TENANT_ID}-{schedule_suffix}"
    api("POST", "/cloudmold/ai-operations/temporal-schedules/" + urllib.parse.quote(schedule_id, safe="") + "/trigger")
    return {"kind": kind, "candidateId": candidate.get("candidateId"), "status": candidate.get("status"), "scheduleId": schedule_id, "sequence": sequence}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--rounds", type=int, default=1)
    parser.add_argument("--round-size", type=int, default=4)
    args = parser.parse_args()
    builders = {"stock-count": stock_count_payload, "scrap": scrap_payload, "inventory-control": control_payload, "supplier-admission": supplier_admission_payload, "warehouse-transfer": warehouse_transfer_payload}
    rotation = ["stock-count", "scrap", "warehouse-transfer", "supplier-admission", "inventory-control"]
    results: list[dict] = []
    sequence = 0
    for round_index in range(max(1, args.rounds)):
        for item_index in range(max(1, args.round_size)):
            kind = rotation[(round_index * max(1, args.round_size) + item_index) % len(rotation)]
            sequence += 1
            try:
                results.append(enqueue(kind, builders[kind](sequence), sequence))
            except Exception as error:
                results.append({"kind": kind, "status": "SKIPPED", "sequence": sequence, "reason": str(error)})
    print(json.dumps({"tenantId": TENANT_ID, "results": results}, ensure_ascii=False))
    return 0


